# Renders the manual pages (../../man) into the site with mandoc:
# src/man/<page>-<sec>.html (the HTML fragment) and
# src/content/docs/reference/man/<page>-<sec>.mdx (the page that shows it).
# Cross references to pages noqtis does not ship (memcmp(3), ...) are left
# as text. Run from docs/site; needs mandoc. NQBASE as in astro.config.mjs.
set -eu
BASE=${NQBASE:-/noqtis}
BASE=${BASE%/}
MAN=../../man
OUT=src/man
DOC=src/content/docs/reference/man
command -v mandoc > /dev/null || { echo "man.sh: mandoc is needed" >&2; exit 2; }
mkdir -p "$OUT" "$DOC"
rm -f "$OUT"/*.html "$DOC"/*.mdx
have=" "
for f in "$MAN"/*.[135]; do
  b=$(basename "$f")
  have="$have${b%.*}-${b##*.} "
done
for f in "$MAN"/*.[135]; do
  b=$(basename "$f")
  n=${b%.*}
  s=${b##*.}
  id="$n-$s"
  nd=$(sed -n 's/^\.Nd //p' "$f" | sed 's/"/\\"/g')
  mandoc -Thtml -Ofragment,man="$BASE/reference/man/%N-%S/" "$f" |
    HAVE="$have" BASE="$BASE" perl -0pe '
      # the running head and foot repeat the title Starlight already shows
      s{<table class="head">.*?</table>\s*}{}s;
      s{<table class="foot">.*?</table>\s*}{}s;
      # links only to pages we ship
      s{<a class="Xr" href="\Q$ENV{BASE}\E/reference/man/([^/"]+)/">(.*?)</a>}
       { index($ENV{HAVE}, " $1 ") >= 0
           ? qq{<a class="Xr" href="$ENV{BASE}/reference/man/$1/">$2</a>}
           : qq{<span class="Xr">$2</span>} }ge;
    ' > "$OUT/$id.html"
  case $s in
  1) order=1 ;;
  3) order=3 ;;
  *) order=5 ;;
  esac
  case $n in
  noqtis) order=0 ;;
  esac
  cat > "$DOC/$id.mdx" << EOF
---
title: "$n($s)"
description: "$nd"
sidebar:
  order: $order
editUrl: https://github.com/rootcoder007/noqtis/edit/main/man/$b
tableOfContents: false
---
import page from "../../../../man/$id.html?raw";

{/* Generated by docs/site/scripts/man.sh from man/$b; edit that file. */}

<div class="nqman" set:html={page} />
EOF
done
echo "man.sh: $(ls "$DOC" | wc -l | tr -d ' ') pages"
