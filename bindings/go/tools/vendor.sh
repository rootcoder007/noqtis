# Copies the noqtis C library (../../src/*/ and ../../include/noqtis.h)
# into csrc/ and writes one nq_<module>_<file>.c per source file, which
# includes it: cgo compiles only the .c files in the package's own folder,
# and a module fetched with `go get` holds only this folder, so the copy
# is committed. Run from anywhere; rerun after any change to the library
# (go.yml fails when the copy is out of date).
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
top=$(cd "$here/../.." && pwd)
test -f "$top/include/noqtis.h" || {
  echo "vendor.sh: $top/include/noqtis.h not found" >&2
  exit 2
}
rm -rf "$here/csrc"
rm -f "$here"/nq_*.c
mkdir -p "$here/csrc/src" "$here/csrc/include"
cp "$top/include/noqtis.h" "$here/csrc/include/"
n=0
for d in "$top"/src/*/; do
  m=$(basename "$d")
  mkdir "$here/csrc/src/$m"
  for f in "$d"*.c "$d"*.h; do
    test -f "$f" && cp "$f" "$here/csrc/src/$m/"
  done
  for f in "$d"*.c; do
    test -f "$f" || continue
    b=$(basename "$f" .c)
    {
      echo "// Generated by tools/vendor.sh; do not edit."
      echo "#include \"csrc/src/$m/$b.c\""
    } > "$here/nq_${m}_$b.c"
    n=$((n + 1))
  done
done
cp "$top/LICENSE" "$top/NOTICE" "$here/"
echo "vendor.sh: copied src/ and include/noqtis.h; $n sources"
