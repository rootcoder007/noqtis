test_that("a module is named by a path", {
  expect_error(nqtoken("nqtok"))
  expect_error(nqtoken("./no/such/module.so"))
  expect_error(nqtoken(1), "path of a PKCS #11 module")
  expect_error(nqtokens("x"), "token from nqtoken")
  expect_error(nqtokenlogin(NULL, "a"), "one slot number")
})

test_that("keys on a token sign and decapsulate", {
  mod <- Sys.getenv("NQTOKPATH")
  skip_if(!nzchar(mod), "NQTOKPATH is not set")
  t <- nqtoken(mod)
  expect_output(print(t), "noqtis token")
  ts <- nqtokens(t)
  expect_identical(nrow(ts), 1L)
  expect_identical(ts$label, "noqtis test token")
  expect_true(ts$login)
  expect_error(nqtokenlogin(t, ts$slot, "0000"))
  expect_null(nqtokenlogin(t, ts$slot, "1234"))
  k <- nqtokenkeygen(t, "ML-DSA-65", "r-sig")
  expect_identical(k$alg, "ML-DSA-65")
  expect_false(k$kem)
  expect_identical(k$label, "r-sig")
  pk <- nqtokenpub(t, k)
  msg <- charToRaw("signed on the token")
  sig <- nqtokensign(t, k, msg, ctx = "ctx")
  expect_true(nqverify(pk, msg, sig, "ML-DSA-65", ctx = charToRaw("ctx")))
  expect_false(nqverify(pk, msg, sig, "ML-DSA-65"))
  kk <- nqtokenkeygen(t, "ML-KEM-768", "r-kem")
  e <- nqencap(nqtokenpub(t, kk), "ML-KEM-768")
  expect_identical(nqtokendecap(t, kk, e$ct), e$ss)
  expect_error(nqtokenkeygen(t, "HQC-128", "x"))
  expect_error(nqtokensign(t, kk, msg))
  expect_error(nqtokensign(t, "key", msg), "one row")
  expect_error(nqtokendecap(t, k, raw(10)), "not a KEM key")
  # a key with no identifier is asked for by its handle alone
  noid <- k
  noid$id <- ""
  expect_error(nqtokenpub(t, noid), "nqp11pub")
  cc <- function(f, ...) .Call(get(f, envir = asNamespace("noqtis")), ...)
  p <- get(".tokptr", envir = asNamespace("noqtis"))(t)
  expect_error(cc("Cp11login", p, "x", NULL), "'slot' must be one number")
  expect_error(cc("Cp11login", p, -1, NULL), "whole number from 0")
  expect_gte(nrow(nqtokenkeys(t)), 2L)
  expect_null(nqtokenclose(t))
  expect_error(nqtokens(t), "closed")
  expect_null(nqtokenclose(t))
})
