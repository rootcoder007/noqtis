sealed <- function() {
  d <- tempfile("nqx")
  dir.create(file.path(d, "data"), recursive = TRUE)
  writeLines(c("id,x", "1,0.5", "2,1.5", "3,2.5", "4,3"),
             file.path(d, "data", "a.csv"))
  d
}

test_that("inspect and sealwhy", {
  d <- sealed()
  on.exit(unlink(d, recursive = TRUE))
  expect_null(nqsealwhy(d))
  k <- nqkeygen("ML-DSA-44")
  if (.Platform$OS.type == "unix") {
    file.symlink("data", file.path(d, "l"))
    expect_error(nqseal(d, k$sk, k$pk, "ML-DSA-44"))
    expect_identical(nqsealwhy(d), list(why = "link", path = "l"))
    unlink(file.path(d, "l"))
  }
  nqseal(d, k$sk, k$pk, "ML-DSA-44")
  i <- nqinspect(d)
  expect_identical(i$detail[i$check == "info.alg"], "ML-DSA-44")
  expect_identical(i$detail[i$check == "info.timestamp"], "none")
  q <- nqtsreq(d, nonce = as.raw(1:2))
  expect_identical(q[1], as.raw(0x30))
  expect_false(identical(q, nqtsreq(d)))
  expect_identical(nqersreq(d)[1], as.raw(0x30))
  # the hash of the record is the caller's to choose
  h <- nqersreq(d, hash = "sha512")
  expect_identical(h[1], as.raw(0x30))
  expect_false(identical(h, nqersreq(d, hash = "sha256")))
  expect_error(nqersput(d, as.raw(c(0x30, 0)), hash = "sha512"))
  expect_error(nqersreq(d, hash = "md5"), "unknown hash")
  expect_error(nqtsput(d, as.raw(c(0x30, 0))))
  expect_error(nqersput(d, as.raw(c(0x30, 0))))
  expect_error(nqtsreq(d, nonce = "x"), "raw vector")
})

test_that("bundles round-trip and refuse a cut one", {
  d <- sealed()
  w <- tempfile("nqw")
  dir.create(w)
  on.exit(unlink(c(d, w), recursive = TRUE))
  k <- nqkeygen("ML-DSA-44")
  nqdadd(d, "data/a.csv")
  nqseal(d, k$sk, k$pk, "ML-DSA-44")
  a <- file.path(w, "a.nqb")
  b <- file.path(w, "b.nqb")
  nqpack(d, a)
  nqpack(d, b)
  expect_identical(readBin(a, "raw", 1e6), readBin(b, "raw", 1e6))
  expect_true(attr(nqcheckpack(a, k$pk), "ok"))
  nqunpack(a, file.path(w, "u"))
  expect_true(attr(nqcheck(file.path(w, "u"), k$pk), "ok"))
  expect_error(nqunpack(a, file.path(w, "u")))
  x <- readBin(a, "raw", 1e6)
  writeBin(x[seq_len(length(x) - 10L)], file.path(w, "cut"))
  expect_error(nqunpack(file.path(w, "cut"), file.path(w, "v")))
  expect_false(dir.exists(file.path(w, "v")))
  ds <- character(0)
  for (i in 1:3) {
    l <- file.path(w, paste0("l", i))
    dir.create(l)
    writeLines(paste("entry", i), file.path(l, "log.txt"))
    inp <- if (length(ds)) c(prev = ds[length(ds)]) else NULL
    nqseal(l, k$sk, k$pk, "ML-DSA-44", format = 2L, inputs = inp)
    ds <- c(ds, l)
  }
  ch <- nqchain(ds, k$pk)
  expect_true(attr(ch, "ok"))
  expect_identical(attr(ch, "head"), nqcapid(ds[3]))
  gap <- nqchain(ds[c(1, 3)], k$pk)
  expect_false(attr(gap, "ok"))
  expect_null(attr(gap, "head"))
})

test_that("parse, schema checks, stand-ins, calibration and chunks", {
  d <- sealed()
  on.exit(unlink(d, recursive = TRUE))
  expect_identical(nqdparse('{ "format" : "noqtis-data-1" }'),
                   '{"format":"noqtis-data-1"}')
  expect_error(nqdparse('{"format":"x"}'), "format")
  s <- nqschema(d, "data/a.csv")
  expect_true(attr(nqdschk(d, s), "ok"))
  expect_false(attr(nqdschk(d, sub('"int"', '"bool"', s, fixed = TRUE)),
                    "ok"))
  nqdput(d, "schemas", s)
  nqdadd(d, "data/a.csv")
  expect_error(nqdsyn(d, "data/a.csv", seed = 1), "synthetic")
  nqdput(d, "schemas", sub("data/a.csv", "data/s.csv", s, fixed = TRUE))
  nqdsyn(d, "data/s.csv", seed = 7)
  one <- readLines(file.path(d, "data", "s.csv"))
  nqdsyn(d, "data/s.csv", seed = 7)
  expect_identical(readLines(file.path(d, "data", "s.csv")), one)
  expect_length(one, 5L)
  expect_true(attr(nqdcheck(d), "ok"))
  expect_error(nqdsyn(d, "data/s.csv", seed = -1), "whole number")
  nqdpin(d, "data/a.csv")
  e <- nqdcal(d, "data/a.csv", file.path(d, "data", "a.csv"))
  expect_match(e, '"cal"', fixed = TRUE)
  expect_true(attr(nqdrift(d), "ok"))
  big <- as.raw(seq_len(5000L) %% 253L)
  writeBin(big, file.path(d, "big.bin"))
  expect_match(nqdchunk(d, "big.bin", 1024), '"size":5000', fixed = TRUE)
  p <- tempfile()
  writeBin(big[2049:5000], p)
  expect_true(attr(nqdpiece(d, "big.bin", p, 2048), "ok"))
  writeBin(flip(big[2049:5000], 1100L), p)
  r <- nqdpiece(d, "big.bin", p, 2048)
  expect_false(attr(r, "ok"))
  expect_identical(r$check[1], "chunk")
  unlink(p)
  expect_error(nqdchunk(d, "big.bin", 10))
})

test_that("commitments, citation, report and the environment", {
  d <- sealed()
  on.exit(unlink(d, recursive = TRUE))
  plan <- "arm A: 1, 4\narm B: 2, 3\n"
  s <- nqdcommit(d, plan, kind = "randomisation", label = "trial")
  expect_length(s, 32L)
  expect_identical(nqdreveal(d, plan, s), 1L)
  expect_identical(nqdreveal(d, "other", s), NA_integer_)
  expect_identical(nqdreveal(d, plan, raw(32)), NA_integer_)
  expect_error(nqdcommit(d, plan, after = "soon"), "UTC time")
  expect_error(nqdcite(d), "could not be read")
  nqdput(d, "cite", paste0('{"title":"T","authors":["A. Author"],',
                           '"year":2026,"doi":"10.1234/x"}'))
  expect_match(nqdcite(d), 'title: "T"', fixed = TRUE)
  expect_match(nqdcite(d, "bibtex"), "doi = {10.1234/x}", fixed = TRUE)
  writeLines("{}", file.path(d, "renv.lock"))
  e <- nqdenv(d, rng = "Mersenne-Twister", seed = 42,
              pkgs = list2DF(list(name = c("z", "a"), version = c("1", "2"),
                                  source = c("CRAN", "CRAN"))))
  j <- nqdata(d)
  expect_match(j, '"language":"r"', fixed = TRUE)
  expect_match(j, '"packages":[{"name":"a"', fixed = TRUE)
  expect_match(j, '"rng":{"kind":"Mersenne-Twister","seed":42}', fixed = TRUE)
  expect_match(j, '"locks":[{"path":"renv.lock"', fixed = TRUE)
  # factors are taken as their labels; list columns and NA are refused
  f <- list2DF(list(name = factor("b"), version = factor("3"), source = "x"))
  expect_match(nqdenv(d, pkgs = f), '"name":"b","version":"3"', fixed = TRUE)
  l <- list2DF(list(name = "a", version = "1", source = "x"))
  l$source <- list("x")
  expect_error(nqdenv(d, pkgs = l), "list columns")
  na <- list2DF(list(name = NA, version = "1", source = "x"))
  expect_error(nqdenv(d, pkgs = na), "NA")
  expect_error(nqdenv(d, pkgs = list()), "data frame")
  nqdenv(d)
  expect_true("noqtis" %in% nqdpkgs()$name)
  # the packages named, in order of name
  two <- nqdpkgs(c("utils", "stats"))
  expect_identical(two$name, c("stats", "utils"))
  expect_identical(two$source, c("base", "base"))
  expect_true(attr(nqdcheck(d), "ok"))
  expect_error(nqdenv(d, locks = "none.lock"), "files in")
  expect_error(nqdreport(d), NA)
  k <- nqkeygen("ML-DSA-44")
  nqseal(d, k$sk, k$pk, "ML-DSA-44")
  md <- nqdreport(d, k$pk)
  expect_match(md, "^#")
  expect_match(nqdreport(d, format = "txt"), "data", fixed = TRUE)
})

test_that("outputs hold no missing values, and edge inputs fail clearly", {
  k <- nqkeygen("ML-DSA-44")
  expect_false(anyNA(nqdpkgs()))
  expect_length(nqblake2b(raw(0)), 64L)
  expect_length(nqsignmu(k$sk, nqmu(k$pk, raw(0), "ML-DSA-44"), "ML-DSA-44"),
                nqalgs()$sig[nqalgs()$name == "ML-DSA-44"])
  # an all-missing column and a constant one keep their schema
  d <- tempfile("nqna")
  dir.create(d)
  on.exit(unlink(d, recursive = TRUE))
  writeLines(c("id,x,y", "1,NA,7", "2,,7", "3,NA,7"), file.path(d, "a.csv"))
  s <- nqschema(d, "a.csv")
  expect_match(s, '"name":"x","nulls":true', fixed = TRUE)
  expect_true(attr(nqdschk(d, s), "ok"))
  nqdput(d, "schemas", s)
  nqdpin(d, "a.csv")
  expect_true(attr(nqdrift(d), "ok"))
  expect_error(nqblake2b(complex(1)), "raw vector or one string")
  expect_error(nqdsyn(d, "a.csv", seed = 1.5), "whole number")
})

test_that("trivial noise does not change a drift verdict", {
  d <- tempfile("nqnoise")
  dir.create(d)
  on.exit(unlink(d, recursive = TRUE))
  x <- seq(0.5, 300, by = 0.25)
  writeLines(c("x", sprintf("%.17g", x)), file.path(d, "a.csv"))
  nqdpin(d, "a.csv")
  n <- file.path(d, "n.csv")
  writeLines(c("x", sprintf("%.17g", x * (1 + 4 * .Machine$double.eps))), n)
  r <- nqdrift(d, "a.csv", current = n)
  expect_true(attr(r, "ok"))
  expect_identical(attr(r, "level"), "ok")
})
