# Copies the noqtis C library (../../src/*/ and ../../include/noqtis.h)
# into this R package's src/, and writes src/Makevars and src/Makevars.win
# with the object list, so the package builds on its own (no system
# libnoqtis). Run from anywhere; rerun after any change to the library.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
top=$(cd "$here/../.." && pwd)
dst="$here/src"

test -f "$top/include/noqtis.h" || {
  echo "vendor.sh: $top/include/noqtis.h not found" >&2
  exit 2
}

# remove what an earlier run copied (every folder in src/ is vendored)
for d in "$dst"/*/; do
  test -d "$d" && rm -rf "$d"
done

mods=""
for d in "$top"/src/*/; do
  m=$(basename "$d")
  mkdir "$dst/$m"
  for f in "$d"*.c "$d"*.h; do
    test -f "$f" && cp "$f" "$dst/$m/"
  done
  mods="$mods $m"
done
mkdir "$dst/include"
cp "$top/include/noqtis.h" "$dst/include/"

objs="rnq.o"
for m in $mods; do
  for f in "$dst/$m"/*.c; do
    test -f "$f" || continue
    b=$(basename "$f" .c)
    objs="$objs $m/$b.o"
  done
done

# one object per line, so a change shows up as a one-line diff
list=$(printf '%s\n' $objs | sed 's/$/ \\/' | sed '$ s/ \\$//' |
  sed 's/^/  /')

write() {
  {
    echo "# Generated by tools/vendor.sh; do not edit."
    echo "PKG_CPPFLAGS = -I. -Iinclude"
    if test -n "$2"; then
      echo "PKG_LIBS = $2"
    fi
    echo "OBJECTS = \\"
    echo "$list"
  } > "$1"
}

write "$dst/Makevars" ""
# BCryptGenRandom (the CSPRNG nqrand uses on Windows) is in bcrypt
write "$dst/Makevars.win" "-lbcrypt"

n=$(printf '%s\n' $objs | wc -l | tr -d ' ')
echo "vendor.sh: copied$mods and include/noqtis.h; $n objects"
