# Copies the noqtis C library (../../src/*/ and ../../include/noqtis.h)
# and its data layer (../../nqd/ and ../../include/nqd.h) into this R
# package's src/, and writes src/Makevars.in and src/Makevars.win.in
# (configure and configure.win make Makevars of them) with the object list, so the package builds on its own (no system
# libnoqtis). Run from anywhere; rerun after any change to the library.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
top=$(cd "$here/../.." && pwd)
dst="$here/src"

test -f "$top/include/noqtis.h" || {
  echo "vendor.sh: $top/include/noqtis.h not found" >&2
  exit 2
}

# remove what an earlier run copied (every folder in src/ is vendored)
for d in "$dst"/*/; do
  test -d "$d" && rm -rf "$d"
done

mods=""
for d in "$top"/src/*/; do
  m=$(basename "$d")
  mkdir "$dst/$m"
  for f in "$d"*.c "$d"*.h; do
    test -f "$f" && cp "$f" "$dst/$m/"
  done
  mods="$mods $m"
done
# the data layer, a library of its own beside the core
mkdir "$dst/nqd"
cp "$top"/nqd/*.c "$top"/nqd/*.h "$dst/nqd/"
mods="$mods nqd"
mkdir "$dst/include"
cp "$top/include/noqtis.h" "$top/include/nqd.h" "$dst/include/"

objs="rnq.o rnqd.o"
for m in $mods; do
  for f in "$dst/$m"/*.c; do
    test -f "$f" || continue
    b=$(basename "$f" .c)
    objs="$objs $m/$b.o"
  done
done

# one object per line, so a change shows up as a one-line diff
list=$(printf '%s\n' $objs | sed 's/$/ \\/' | sed '$ s/ \\$//' |
  sed 's/^/  /')

write() {
  {
    echo "# Generated by tools/vendor.sh; do not edit."
    echo "# configure writes $(basename "${1%.in}") from this, with @NQCF@"
    echo "# the floating-point flags the compiler takes."
    echo "PKG_CPPFLAGS = -I. -Iinclude"
    echo "PKG_CFLAGS = @NQCF@"
    if test -n "$2"; then
      echo "PKG_LIBS = $2"
    fi
    echo "OBJECTS = \\"
    echo "$list"
  } > "$1"
}

write "$dst/Makevars.in" ""
# BCryptGenRandom (the CSPRNG nqrand uses on Windows) is in bcrypt
write "$dst/Makevars.win.in" "-lbcrypt"

n=$(printf '%s\n' $objs | wc -l | tr -d ' ')
echo "vendor.sh: copied$mods, include/noqtis.h and nqd.h; $n objects"
